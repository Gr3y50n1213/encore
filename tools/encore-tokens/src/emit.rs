//! Writes the token tree as Swift, Kotlin and Dart source.
//!
//! Shape of the output, for `{"breakpoints": {"railWidth": 80}}`:
//! - Swift:  `EncoreTokens.Breakpoints.railWidth` (nested enums with `static let`)
//! - Kotlin: `EncoreTokens.Breakpoints.railWidth` (nested objects with `const val`)
//! - Dart:   `EncoreTokens.breakpoints.railWidth` (Dart has no nested classes, so
//!   each group is a const class named after its path, e.g. `EncoreTokensBreakpoints`)

use crate::model::{Entry, Field, FieldType, Group, Kind, Records, Scalar};
use crate::names::{camel, dart_member, kotlin_member, pascal, swift_member, swift_type_name};

pub const ROOT: &str = "EncoreTokens";

const HEADER: &str = "Generated by tools/encore-tokens from design/tokens.json. Do not edit by hand.\n\
                      Change tokens.json, then run `make tokens` in core/.";

struct Out {
    buf: String,
    unit: &'static str,
}

impl Out {
    fn new(unit: &'static str) -> Self {
        Out {
            buf: String::new(),
            unit,
        }
    }

    fn line(&mut self, depth: usize, text: &str) {
        if !text.is_empty() {
            for _ in 0..depth {
                self.buf.push_str(self.unit);
            }
            self.buf.push_str(text);
        }
        self.buf.push('\n');
    }

    fn comment_header(&mut self) {
        for l in HEADER.lines() {
            self.line(0, &format!("// {}", l.trim()));
        }
    }
}

fn float(f: f64) -> String {
    // Debug formatting is the shortest text that reads back as the same f64 and
    // always has a decimal point or an exponent, which all three languages accept.
    format!("{f:?}")
}

/// `dollar`: escape `$` (Kotlin and Dart templates). `kotlin`: `\uXXXX` instead of `\u{X}`.
fn escape(s: &str, quote: char, dollar: bool, kotlin: bool) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '$' if dollar => out.push_str("\\$"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            c if c.is_control() && kotlin => out.push_str(&format!("\\u{:04x}", c as u32)),
            c if c.is_control() => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

fn first_is_group(i: usize, entry: &Entry) -> bool {
    i > 0 && !matches!(entry, Entry::Field(_))
}

// ---------------------------------------------------------------- Swift

fn swift_kind(k: Kind) -> &'static str {
    match k {
        Kind::Int => "Int",
        Kind::Float => "Double",
        Kind::Bool => "Bool",
        Kind::Str => "String",
    }
}

fn swift_scalar(s: &Scalar) -> String {
    match s {
        Scalar::Int(i) => i.to_string(),
        Scalar::Float(f) => float(*f),
        Scalar::Bool(b) => b.to_string(),
        Scalar::Str(s) => format!("\"{}\"", escape(s, '"', false, false)),
    }
}

fn swift_field(f: &Field) -> (String, String) {
    match f {
        Field::One(s) => (swift_kind(s.kind()).to_string(), swift_scalar(s)),
        Field::List(k, v) => (
            format!("[{}]", swift_kind(*k)),
            format!(
                "[{}]",
                v.iter().map(swift_scalar).collect::<Vec<_>>().join(", ")
            ),
        ),
    }
}

fn swift_type(t: FieldType) -> String {
    match t {
        FieldType::One(k) => swift_kind(k).to_string(),
        FieldType::List(k) => format!("[{}]", swift_kind(k)),
    }
}

fn swift_docs(out: &mut Out, depth: usize, docs: &[String]) {
    for d in docs {
        for l in d.lines() {
            out.line(depth, &format!("/// {l}"));
        }
    }
}

pub fn swift(root: &Group) -> String {
    let mut out = Out::new("    ");
    out.comment_header();
    out.line(0, "// swiftlint:disable all");
    out.line(0, "");
    swift_docs(&mut out, 0, &root.docs);
    out.line(0, &format!("public enum {ROOT} {{"));
    swift_body(&mut out, 1, root);
    out.line(0, "}");
    out.buf
}

fn swift_body(out: &mut Out, depth: usize, group: &Group) {
    for (i, (key, entry)) in group.entries.iter().enumerate() {
        if first_is_group(i, entry) {
            out.line(0, "");
        }
        match entry {
            Entry::Field(f) => {
                let (ty, value) = swift_field(f);
                out.line(
                    depth,
                    &format!("public static let {}: {ty} = {value}", swift_member(key)),
                );
            }
            Entry::Group(g) => {
                swift_docs(out, depth, &g.docs);
                out.line(depth, &format!("public enum {} {{", swift_type_name(key)));
                swift_body(out, depth + 1, g);
                out.line(depth, "}");
            }
            Entry::Records(r) => swift_records(out, depth, key, r),
        }
    }
}

fn swift_records(out: &mut Out, depth: usize, key: &str, r: &Records) {
    let item = format!("{}Item", pascal(key));
    out.line(
        depth,
        &format!("public struct {item}: Sendable, Equatable {{"),
    );
    for (name, ty) in &r.fields {
        out.line(
            depth + 1,
            &format!("public let {}: {}", swift_member(name), swift_type(*ty)),
        );
    }
    out.line(depth, "}");
    out.line(
        depth,
        &format!("public static let {}: [{item}] = [", swift_member(key)),
    );
    for row in &r.rows {
        let args: Vec<String> = r
            .fields
            .iter()
            .zip(row)
            .map(|((name, _), f)| format!("{}: {}", camel(name), swift_field(f).1))
            .collect();
        out.line(depth + 1, &format!("{item}({}),", args.join(", ")));
    }
    out.line(depth, "]");
}

// ---------------------------------------------------------------- Kotlin

fn fits_i32(i: i64) -> bool {
    i32::try_from(i).is_ok()
}

fn kotlin_kind(k: Kind, long: bool) -> &'static str {
    match k {
        Kind::Int if long => "Long",
        Kind::Int => "Int",
        Kind::Float => "Double",
        Kind::Bool => "Boolean",
        Kind::Str => "String",
    }
}

fn kotlin_scalar(s: &Scalar, long: bool) -> String {
    match s {
        Scalar::Int(i) if long => format!("{i}L"),
        Scalar::Int(i) => i.to_string(),
        Scalar::Float(f) => float(*f),
        Scalar::Bool(b) => b.to_string(),
        Scalar::Str(s) => format!("\"{}\"", escape(s, '"', true, true)),
    }
}

fn needs_long(values: &[Scalar]) -> bool {
    values
        .iter()
        .any(|v| matches!(v, Scalar::Int(i) if !fits_i32(*i)))
}

/// Returns (type, value, is_const).
fn kotlin_field(f: &Field, long: bool) -> (String, String, bool) {
    match f {
        Field::One(s) => {
            let long = long || needs_long(std::slice::from_ref(s));
            (
                kotlin_kind(s.kind(), long).to_string(),
                kotlin_scalar(s, long),
                true,
            )
        }
        Field::List(k, v) => {
            let long = long || needs_long(v);
            (
                format!("List<{}>", kotlin_kind(*k, long)),
                format!(
                    "listOf({})",
                    v.iter()
                        .map(|s| kotlin_scalar(s, long))
                        .collect::<Vec<_>>()
                        .join(", ")
                ),
                false,
            )
        }
    }
}

fn kotlin_docs(out: &mut Out, depth: usize, docs: &[String]) {
    let lines: Vec<String> = docs
        .iter()
        .flat_map(|d| d.lines().map(|l| l.replace("*/", "* /")))
        .collect();
    match lines.as_slice() {
        [] => {}
        [one] => out.line(depth, &format!("/** {one} */")),
        many => {
            out.line(depth, "/**");
            for l in many {
                out.line(depth, &format!(" * {l}"));
            }
            out.line(depth, " */");
        }
    }
}

pub fn kotlin(root: &Group, package: &str) -> String {
    let mut out = Out::new("    ");
    out.comment_header();
    out.line(0, "@file:Suppress(\"unused\")");
    out.line(0, "");
    out.line(0, &format!("package {package}"));
    out.line(0, "");
    kotlin_docs(&mut out, 0, &root.docs);
    out.line(0, &format!("object {ROOT} {{"));
    kotlin_body(&mut out, 1, root);
    out.line(0, "}");
    out.buf
}

fn kotlin_body(out: &mut Out, depth: usize, group: &Group) {
    for (i, (key, entry)) in group.entries.iter().enumerate() {
        if first_is_group(i, entry) {
            out.line(0, "");
        }
        match entry {
            Entry::Field(f) => {
                let (ty, value, is_const) = kotlin_field(f, false);
                let decl = if is_const { "const val" } else { "val" };
                out.line(
                    depth,
                    &format!("{decl} {}: {ty} = {value}", kotlin_member(key)),
                );
            }
            Entry::Group(g) => {
                kotlin_docs(out, depth, &g.docs);
                out.line(depth, &format!("object {} {{", pascal(key)));
                kotlin_body(out, depth + 1, g);
                out.line(depth, "}");
            }
            Entry::Records(r) => kotlin_records(out, depth, key, r),
        }
    }
}

fn kotlin_records(out: &mut Out, depth: usize, key: &str, r: &Records) {
    let item = format!("{}Item", pascal(key));
    // A column is Long when any row needs it, so every row agrees on the type.
    let long: Vec<bool> = (0..r.fields.len())
        .map(|c| {
            r.rows.iter().any(|row| match &row[c] {
                Field::One(s) => needs_long(std::slice::from_ref(s)),
                Field::List(_, v) => needs_long(v),
            })
        })
        .collect();
    out.line(depth, &format!("data class {item}("));
    for ((name, ty), long) in r.fields.iter().zip(&long) {
        let ty = match ty {
            FieldType::One(k) => kotlin_kind(*k, *long).to_string(),
            FieldType::List(k) => format!("List<{}>", kotlin_kind(*k, *long)),
        };
        out.line(depth + 1, &format!("val {}: {ty},", kotlin_member(name)));
    }
    out.line(depth, ")");
    out.line(
        depth,
        &format!("val {}: List<{item}> = listOf(", kotlin_member(key)),
    );
    for row in &r.rows {
        let args: Vec<String> = r
            .fields
            .iter()
            .zip(row)
            .zip(&long)
            .map(|(((name, _), f), long)| {
                format!("{} = {}", kotlin_member(name), kotlin_field(f, *long).1)
            })
            .collect();
        out.line(depth + 1, &format!("{item}({}),", args.join(", ")));
    }
    out.line(depth, ")");
}

// ---------------------------------------------------------------- Dart

fn dart_kind(k: Kind) -> &'static str {
    match k {
        Kind::Int => "int",
        Kind::Float => "double",
        Kind::Bool => "bool",
        Kind::Str => "String",
    }
}

fn dart_scalar(s: &Scalar) -> String {
    match s {
        Scalar::Int(i) => i.to_string(),
        Scalar::Float(f) => float(*f),
        Scalar::Bool(b) => b.to_string(),
        Scalar::Str(s) => format!("'{}'", escape(s, '\'', true, false)),
    }
}

/// Returns (type, value). List values are bare `[...]`; callers add `const` where needed.
fn dart_field(f: &Field) -> (String, String) {
    match f {
        Field::One(s) => (dart_kind(s.kind()).to_string(), dart_scalar(s)),
        Field::List(k, v) => (
            format!("List<{}>", dart_kind(*k)),
            format!(
                "[{}]",
                v.iter().map(dart_scalar).collect::<Vec<_>>().join(", ")
            ),
        ),
    }
}

fn dart_docs(out: &mut Out, depth: usize, docs: &[String]) {
    for d in docs {
        for l in d.lines() {
            out.line(depth, &format!("/// {l}"));
        }
    }
}

pub fn dart(root: &Group) -> String {
    let mut out = Out::new("  ");
    out.comment_header();
    out.line(0, "// ignore_for_file: type=lint");
    dart_class(&mut out, ROOT, root, true);
    out.buf
}

fn dart_class(out: &mut Out, class: &str, group: &Group, is_root: bool) {
    out.line(0, "");
    dart_docs(out, 0, &group.docs);
    if is_root {
        out.line(0, &format!("abstract final class {class} {{"));
    } else {
        out.line(0, &format!("final class {class} {{"));
        out.line(1, &format!("const {class}._();"));
        out.line(0, "");
    }
    // Root members are static consts; nested members are final fields of a const object.
    let (decl, konst) = if is_root {
        ("static const ", "")
    } else {
        ("final ", "const ")
    };
    let mut later: Vec<(String, &Group)> = Vec::new();
    let mut records: Vec<(String, &Records)> = Vec::new();
    for (key, entry) in &group.entries {
        let member = dart_member(key);
        match entry {
            Entry::Field(f @ Field::One(_)) => {
                let (ty, value) = dart_field(f);
                out.line(1, &format!("{decl}{ty} {member} = {value};"));
            }
            Entry::Field(f @ Field::List(..)) => {
                let (ty, value) = dart_field(f);
                out.line(1, &format!("{decl}{ty} {member} = {konst}{value};"));
            }
            Entry::Group(g) => {
                let sub = format!("{class}{}", pascal(key));
                out.line(1, &format!("{decl}{sub} {member} = {konst}{sub}._();"));
                later.push((sub, g));
            }
            Entry::Records(r) => {
                let item = format!("{class}{}Item", pascal(key));
                out.line(1, &format!("{decl}List<{item}> {member} = {konst}["));
                for row in &r.rows {
                    let args: Vec<String> = r
                        .fields
                        .iter()
                        .zip(row)
                        .map(|((name, _), f)| format!("{}: {}", dart_member(name), dart_field(f).1))
                        .collect();
                    out.line(2, &format!("{item}({}),", args.join(", ")));
                }
                out.line(1, "];");
                records.push((item, r));
            }
        }
    }
    out.line(0, "}");
    for (item, r) in records {
        dart_record_class(out, &item, r);
    }
    for (sub, g) in later {
        dart_class(out, &sub, g, false);
    }
}

fn dart_record_class(out: &mut Out, item: &str, r: &Records) {
    out.line(0, "");
    out.line(0, &format!("final class {item} {{"));
    let params: Vec<String> = r
        .fields
        .iter()
        .map(|(n, _)| format!("required this.{}", dart_member(n)))
        .collect();
    out.line(1, &format!("const {item}({{{}}});", params.join(", ")));
    out.line(0, "");
    for (name, ty) in &r.fields {
        let ty = match ty {
            FieldType::One(k) => dart_kind(*k).to_string(),
            FieldType::List(k) => format!("List<{}>", dart_kind(*k)),
        };
        out.line(1, &format!("final {ty} {};", dart_member(name)));
    }
    out.line(0, "}");
}

